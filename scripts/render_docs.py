def load(name: str):
    return json.loads((ROOT / "planning" / name).read_text(encoding="utf-8"))


def bullet(items):
    return "\n".join(f"- {item}" for item in items)


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def table(headers, rows):
    return "\n".join([
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(cell(v) for v in row) + " |" for row in rows),
    ])


def published_issue_urls(publication):
    """Use only recorded issue URLs; an absent/partial map is valid during publication."""
    supplied = publication.get("issue_urls", {})
    if not isinstance(supplied, dict):
        raise ValueError("PUBLICATION.json issue_urls must be a mapping of plan IDs to recorded issue URLs")
    urls = {}
    for plan_id, value in supplied.items():
        if isinstance(value, dict):
            value = value.get("url", value.get("html_url"))
        if not isinstance(value, str) or not re.fullmatch(r"https://github\.com/[^/\s?#]+/[^/\s?#]+/issues/[1-9][0-9]*", value):
            raise ValueError(f"PUBLICATION.json has an invalid recorded issue URL for {plan_id}")
        urls[plan_id] = value
    return urls


def issue_link(plan_id, issue_urls, label=None):
    label = label or plan_id
    return f"[{label}]({issue_urls[plan_id]})" if plan_id in issue_urls else label


def json_detail(value, depth=3):
    """Readable full detail; retain every definition and policy field."""
    if isinstance(value, dict):
        parts = []
        for key, item in value.items():
            title = key.replace("_", " ").capitalize()
            if isinstance(item, (dict, list)):
                parts.append(f"{'#' * min(depth, 6)} {title}\n\n{json_detail(item, depth + 1)}")
            else:
                parts.append(f"**{title}:** {item}")
        return "\n\n".join(parts)
    if isinstance(value, list):
        if all(not isinstance(item, (dict, list)) for item in value):
            return bullet(value)
        return "\n\n".join(json_detail(item, depth) for item in value)
    return str(value)


